def _norm(value: object) -> str:
    return "" if value is None else str(value).strip()


def _business_row_present(ws, row: int) -> bool:
    return any(_norm(ws.cell(row, col).value) for col in BUSINESS_COLS)


def _row_has_visible_month_cost(ws, row: int) -> bool:
    return worksheet_row_has_cost(ws, row, MONTH_COLS)


def _staged_row_has_month_payload(row: StagedWorkbookRow) -> bool:
    return any(_norm(row.values.get(col)) for col in MONTH_COLS)


def _fill_rgb(cell) -> str:
    color = cell.fill.fgColor
    return str(color.rgb or "") if color.type == "rgb" else ""


def _copy_staged_row(
    ws,
    source_file: str,
    row: int,
    original_row: int | None = None,
    *,
    require_visible_month_cost: bool = True,
    source_order_managed: bool = True,
) -> StagedWorkbookRow | None:
    if require_visible_month_cost and not _row_has_visible_month_cost(ws, row):
        return None
    if not require_visible_month_cost and not _business_row_present(ws, row):
        return None
    values: dict[int, object] = {}
    styles: dict[int, object] = {}
    number_formats: dict[int, str] = {}
    for col in COPY_COLS:
        cell = ws.cell(row, col)
        values[col] = cell.value
        if cell.has_style:
            styles[col] = copy(cell._style)
        number_formats[col] = cell.number_format
    return StagedWorkbookRow(
        source_file,
        int(original_row or row),
        int(row),
        values,
        styles,
        number_formats,
        source_order_managed=source_order_managed,
    )


def _clear_business_row(ws, row: int) -> None:
    for col in MANAGED_CLEAR_COLS:
        cell = ws.cell(row, col)
        cell.value = None
        cell.comment = None
        # Red is a semantic alert for the row currently occupying this cell,
        # not part of the physical FORM row.  The source-order rewrite moves
        # different business items onto legacy staging rows (notably row 58),
        # so retaining this fill leaks an old rule's alert into the new item.
        if col in MONTH_COLS and _fill_rgb(cell).endswith("FFC7CE"):
            cell.fill = copy(MONTH_INPUT_FILL)
        if col == NOTE_COL:
            _clear_metadata_note_for_cell(cell)


def _clear_rows(ws, rows: Iterable[int]) -> None:
    for row in rows:
        _clear_business_row(ws, row)


def _translated_formula(value: object, *, original_row: int, target_row: int, col: int) -> object:
    if not (isinstance(value, str) and value.startswith("=")) or original_row == target_row:
        return value
    coordinate = f"{get_column_letter(col)}{original_row}"
    target = f"{get_column_letter(col)}{target_row}"
    try:
        return Translator(value, origin=coordinate).translate_formula(target)
    except Exception:
        return value


def _lookup_name_formula(row: int) -> str:
    return (
        f'=IFERROR(IF(VLOOKUP($B{row},{ACCOUNT_MASTER_SHEET}!$A:$H,'
        f'HLOOKUP($E$5,{ACCOUNT_MASTER_SHEET}!$F$1:$H$2,2,0),0)="","",'
        f'VLOOKUP($B{row},{ACCOUNT_MASTER_SHEET}!$A:$E,2,0)),"")'
    )


def _lookup_group_formula(row: int) -> str:
    return f'=IF(C{row}="","",VLOOKUP($B{row},{ACCOUNT_MASTER_SHEET}!$A:$E,4,0))'


def _ensure_lookup_formulas(ws, row: int) -> None:
    if not _norm(ws.cell(row, ACCOUNT_COL).value) or not _row_has_visible_month_cost(ws, row):
        return
    if not _norm(ws.cell(row, LOOKUP_NAME_COL).value):
        ws.cell(row, LOOKUP_NAME_COL).value = _lookup_name_formula(row)
    if not _norm(ws.cell(row, LOOKUP_GROUP_COL).value):
        ws.cell(row, LOOKUP_GROUP_COL).value = _lookup_group_formula(row)


def _display_description(value: object) -> object:
    text = _norm(value)
    if not text:
        return value
    if text.lower().startswith("alloc:"):
        text = text[len("Alloc:") :].strip()
    return text.split("|", 1)[0].strip()


def _note_text(note: object) -> str:
    if hasattr(note, "value") or hasattr(note, "comment"):
        value = getattr(note, "value", None)
        comment = getattr(note, "comment", None)
        comment_text = getattr(comment, "text", "") if comment else ""
        metadata_text = _metadata_note_for_cell(note)
        return " | ".join(part for part in (_norm(value), _norm(comment_text), _norm(metadata_text)) if part)
    return _norm(note)


def _metadata_sheet(wb, *, create: bool = False):
    if SOURCE_ORDER_METADATA_SHEET in wb.sheetnames:
        return wb[SOURCE_ORDER_METADATA_SHEET]
    if not create:
        return None
    sheet = wb.create_sheet(SOURCE_ORDER_METADATA_SHEET)
    sheet.sheet_state = "veryHidden"
    sheet.cell(1, 1).value = "sheet"
    sheet.cell(1, 2).value = "row"
    sheet.cell(1, 3).value = "note"
    return sheet


def _metadata_row_for_cell(cell) -> int | None:
    wb = cell.parent.parent
    sheet = _metadata_sheet(wb)
    if sheet is None:
        return None
    sheet_name = cell.parent.title
    row_number = int(cell.row)
    for row in range(2, int(sheet.max_row or 1) + 1):
        if sheet.cell(row, 1).value == sheet_name and int(sheet.cell(row, 2).value or 0) == row_number:
            return row
    return None


def _metadata_note_for_cell(cell) -> str:
    metadata_row = _metadata_row_for_cell(cell)
    if metadata_row is None:
        return ""
    sheet = _metadata_sheet(cell.parent.parent)
    if sheet is None:
        return ""
    return _norm(sheet.cell(metadata_row, 3).value)


def _set_metadata_note_for_cell(cell, note: str) -> None:
    sheet = _metadata_sheet(cell.parent.parent, create=True)
    metadata_row = _metadata_row_for_cell(cell)
    if metadata_row is None:
        metadata_row = int(sheet.max_row or 1) + 1
        sheet.cell(metadata_row, 1).value = cell.parent.title
        sheet.cell(metadata_row, 2).value = int(cell.row)
    sheet.cell(metadata_row, 3).value = note


def _clear_metadata_note_for_cell(cell) -> None:
    metadata_row = _metadata_row_for_cell(cell)
    if metadata_row is None:
        return
    sheet = _metadata_sheet(cell.parent.parent)
    if sheet is not None:
        sheet.delete_rows(metadata_row, 1)


def _write_staged_row(ws, target_row: int, staged: StagedWorkbookRow) -> None:
    for col, value in staged.values.items():
        cell = ws.cell(target_row, col)
        if col == DESCRIPTION_COL:
            value = _display_description(value)
        cell.value = _translated_formula(
            value,
            original_row=staged.source_row,
            target_row=target_row,
            col=col,
        )
        if col in staged.styles:
            cell._style = copy(staged.styles[col])
        number_format = staged.number_formats.get(col)
        if number_format:
            cell.number_format = number_format

    if staged.source_order_managed:
        note_cell = ws.cell(target_row, NOTE_COL)
        note = _source_order_note_base(note_cell)
        source_note = f"source_file={staged.source_file}; original_row={staged.original_row}; {SOURCE_ORDER_MARKER}"
        if staged.audit_trail:
            source_note += f"; audit_trail={staged.audit_trail}"
        note_cell.value = None
        note_cell.comment = None
        _set_metadata_note_for_cell(note_cell, f"{note} | {source_note}" if note else source_note)
    for col in staged.red_month_cols:
        ws.cell(target_row, col).fill = copy(MISSING_SEPARATE_COUNT_FILL)
    _ensure_lookup_formulas(ws, target_row)
    ws.cell(target_row, TOTAL_COL).value = f"=SUM(F{target_row}:Q{target_row})"


def _normalize_final_output_layout(ws, start_row: int, end_row: int) -> dict[str, int]:
    cleared_fills = 0
    cleared_item_ids = 0
    for row in range(max(1, int(start_row)), max(int(end_row), int(start_row) - 1) + 1):
        for col in LAYOUT_WHITE_COLUMNS:
            cell = ws.cell(row, col)
            if cell.fill and cell.fill.fill_type:
                cleared_fills += 1
            cell.fill = copy(NO_FILL)
        item_cell = ws.cell(row, ITEM_ID_COL)
        if _norm(item_cell.value):
            item_cell.value = None
            cleared_item_ids += 1
    return {
        "layout_fills_cleared": cleared_fills,
        "item_ids_cleared": cleared_item_ids,
    }


def _last_business_payload_row(ws, start_row: int) -> int:
    for row in range(int(ws.max_row or 0), int(start_row) - 1, -1):
        if _business_row_present(ws, row):
            return row
    return int(start_row) - 1


def _clear_unused_template_formula_tail(ws, start_row: int, end_row: int) -> int:
    """Remove lookup/total formulas below the final concrete payload cheaply."""
    cleared = 0
    for row in range(max(int(start_row), 1), max(int(end_row), 0) + 1):
        if _business_row_present(ws, row):
            continue
        for col in (LOOKUP_NAME_COL, LOOKUP_GROUP_COL, TOTAL_COL):
            cell = ws.cell(row, col)
            value = cell.value
            if cell.data_type == "f" or (isinstance(value, str) and value.startswith("=")):
                cell.value = None
                cleared += 1
    return cleared


def _source_rows_to_clear(ws) -> set[int]:
    rows_to_clear: set[int] = set()
    for _, rows in _resolved_source_row_groups(ws):
        for row in rows:
            if _parse_source_order_note(ws.cell(row, NOTE_COL)) is not None:
                continue
            if _business_row_present(ws, row):
                rows_to_clear.add(row)
    return rows_to_clear


def _collect_staged_rows(ws, source_file_order: tuple[str, ...]) -> list[StagedWorkbookRow]:
    staged: list[StagedWorkbookRow] = []
    for source_index, rows in _resolved_source_row_groups(ws):
        source_file = source_file_order[source_index]
        for row in rows:
            if _has_generated_file_order_policy(ws.cell(row, NOTE_COL)):
                continue
            item = _copy_staged_row(ws, source_file, row, require_visible_month_cost=False)
            if item is not None:
                staged.append(item)
    return staged


def _parse_source_order_note(note: object) -> tuple[str, int] | None:
    match = SOURCE_NOTE_RE.search(_note_text(note))
    if not match:
        return None
    return match.group(1).strip(), int(match.group(2))


def _source_order_note_base(note: object) -> str:
    parts = [
        part.strip()
        for part in _note_text(note).split("|")
        if part.strip() and SOURCE_ORDER_MARKER not in part
    ]
    return " | ".join(parts)


def _collect_existing_source_order_rows(ws, start_row: int, clear_until_row: int) -> list[StagedWorkbookRow]:
    staged: list[StagedWorkbookRow] = []
    seen: set[tuple[str, int, str, str, tuple[str, ...]]] = set()
    for row in range(int(start_row), int(clear_until_row) + 1):
        if _has_generated_file_order_policy(ws.cell(row, NOTE_COL)):
            continue
        parsed = _parse_source_order_note(ws.cell(row, NOTE_COL))
        if parsed is None:
            continue
        source_file, original_row = parsed
        item = _copy_staged_row(ws, source_file, row, original_row, require_visible_month_cost=False)
        if item is not None:
            key = (
                item.source_file,
                item.original_row,
                _norm(item.values.get(ACCOUNT_COL)),
                _norm(item.values.get(DESCRIPTION_COL)),
                tuple(_norm(item.values.get(col)) for col in MONTH_COLS),
            )
            if key in seen:
                continue
            seen.add(key)
            staged.append(item)
    return staged


def _collect_unmarked_facility_depreciation_rows(
    ws,
    start_row: int,
    clear_until_row: int,
    facility_source_file: str,
) -> list[StagedWorkbookRow]:
    """Recover known Facility depreciation rows written after source ordering.

    Some reference-assisted workbooks place the two Facility depreciation rows
    below the normal source blocks without the hidden source-order marker.  The
    accounts themselves are a fixed FORM contract, so recover only those rows;
    all other unmarked rows remain unmanaged and are preserved separately.
    """
    staged: list[StagedWorkbookRow] = []
    for row in range(int(start_row), int(clear_until_row) + 1):
        # Standard staging rows are collected by _collect_staged_rows.  Looking
        # at them again here would create a second copy in legacy layouts.
        if row in FACILITY_STAGING_ROWS:
            continue
        if _parse_source_order_note(ws.cell(row, NOTE_COL)) is not None:
            continue
        if _has_generated_file_order_policy(ws.cell(row, NOTE_COL)):
            continue
        original_row = FACILITY_UNMARKED_DEPRECIATION_ORIGINAL_ROWS.get(
            _norm(ws.cell(row, ACCOUNT_COL).value)
        )
        if original_row is None:
            continue
        item = _copy_staged_row(
            ws,
            facility_source_file,
            row,
            original_row=original_row,
            require_visible_month_cost=True,
        )
        if item is not None:
            staged.append(item)
    return staged


def _has_generated_file_order_policy(note: object) -> bool:
    text = _note_text(note)
    return any(policy in text for policy in GENERATED_FILE_ORDER_POLICIES)


def _collect_preserved_unmanaged_rows(
    ws,
    start_row: int,
    clear_until_row: int,
    *,
    source_rows_to_clear: set[int],
) -> list[StagedWorkbookRow]:
    preserved: list[StagedWorkbookRow] = []
    rows_to_skip = set(source_rows_to_clear)
    for row in range(int(start_row), int(clear_until_row) + 1):
        if row in rows_to_skip:
            continue
        if _parse_source_order_note(ws.cell(row, NOTE_COL)) is not None:
            continue
        if _has_generated_file_order_policy(ws.cell(row, NOTE_COL)):
            continue
        if (
            not _row_has_visible_month_cost(ws, row)
            and not _norm(ws.cell(row, DESCRIPTION_COL).value)
            and not _note_text(ws.cell(row, NOTE_COL))
        ):
            continue
        description = _norm(ws.cell(row, DESCRIPTION_COL).value)
        if description.lower().startswith("alloc:"):
            continue
        item = _copy_staged_row(
            ws,
            "",
            row,
            row,
            require_visible_month_cost=False,
            source_order_managed=False,
        )
        if item is not None:
            preserved.append(item)
    return preserved



def _collect_dynamic_allocation_rows(
    dynamic_allocation_rows: Iterable[dict[str, object]] | None,
    fiscal_periods: Iterable[str] | None,
    source_file_order: tuple[str, ...],
) -> list[StagedWorkbookRow]:
    if not dynamic_allocation_rows or not fiscal_periods:
        return []
    period_to_col = {str(period): MONTH_START_COL + index for index, period in enumerate(fiscal_periods)}
    staged: list[StagedWorkbookRow] = []
    for index, row in enumerate(dynamic_allocation_rows, start=1):
        source_group_index = int(row.get("source_group_index", 5))
        if not 0 <= source_group_index < len(source_file_order):
            raise ValueError(f"Dynamic source group index ngoài manifest: {source_group_index}")
        source_file = str(row.get("source_file") or source_file_order[source_group_index])
        synthetic_row = 10000 + index
        values: dict[int, object] = {
            ACCOUNT_COL: row.get("account_code"),
            DESCRIPTION_COL: row.get("description"),
        }
        highlight_periods = {str(period) for period in (row.get("highlight_periods") or set())}
        explicit_zero_periods = {str(period) for period in (row.get("explicit_zero_periods") or set())}
        red_month_cols: set[int] = set()
        terms_by_period = row.get("terms") or {}
        numeric_by_period = row.get("numeric_months") or row.get("months") or {}
        for period, col in period_to_col.items():
            terms = list((terms_by_period or {}).get(period, []))
            numeric_value = float((numeric_by_period or {}).get(period, 0.0) or 0.0)
            if terms and numeric_value:
                terms.append(str(int(numeric_value)) if numeric_value.is_integer() else str(numeric_value))
            if terms:
                formula = "=" + "+".join(str(term).lstrip("=") for term in terms)
                if len(formula) > MAX_EXCEL_FORMULA_LENGTH:
                    raise ValueError(
                        "Công thức Excel vượt giới hạn 8.192 ký tự; "
                        f"period={period}, description={row.get('description')!r}, length={len(formula)}"
                    )
                values[col] = formula
            elif numeric_value or period in explicit_zero_periods:
                values[col] = numeric_value
            if period in highlight_periods:
                red_month_cols.add(col)
        values[TOTAL_COL] = f"=SUM(F{synthetic_row}:Q{synthetic_row})"
        has_month_payload = any(col in values for col in MONTH_COLS)
        if source_group_index == 6 and has_month_payload:
            if not _norm(values.get(ACCOUNT_COL)):
                raise ValueError("NNN paperwork có chi phí nhưng thiếu account code; dừng xuất để tránh 経費➝NG.")
            if not _norm(values.get(DESCRIPTION_COL)):
                raise ValueError("NNN paperwork có chi phí nhưng thiếu mô tả nguồn; dừng xuất.")
        if not _norm(values.get(DESCRIPTION_COL)) or not _norm(values.get(ACCOUNT_COL)):
            continue
        staged.append(
            StagedWorkbookRow(
                source_file=source_file,
                original_row=synthetic_row,
                source_row=synthetic_row,
                values=values,
                styles={},
                number_formats={},
                source_order_managed=True,
                red_month_cols=frozenset(red_month_cols),
                audit_trail=str(row.get("audit_trail") or ""),
            )
        )
    return staged


def _has_split_accounts(group: list[StagedWorkbookRow]) -> bool:
    account_positions: dict[str, list[int]] = {}
    for index, row in enumerate(group):
        account_code = _norm(row.values.get(ACCOUNT_COL))
        if not account_code:
            continue
        account_positions.setdefault(account_code, []).append(index)
    for positions in account_positions.values():
        if len(positions) <= 1:
            continue
        if max(positions) - min(positions) + 1 != len(positions):
            return True
    return False


def _source_block_sort_key(row: StagedWorkbookRow) -> tuple[str, int, str]:
    return (
        _norm(row.values.get(ACCOUNT_COL)),
        int(row.original_row),
        _norm(_display_description(row.values.get(DESCRIPTION_COL))),
    )


def _search_text(value: object) -> str:
    normalized = unicodedata.normalize("NFKC", _norm(value)).casefold()
    decomposed = unicodedata.normalize("NFD", normalized)
    searchable: list[str] = []
    previous_base_is_latin = False
    for character in decomposed:
        if unicodedata.combining(character):
            if previous_base_is_latin:
                continue
            searchable.append(character)
            continue
        searchable.append(character)
        previous_base_is_latin = "LATIN" in unicodedata.name(character, "")
    return unicodedata.normalize("NFC", "".join(searchable))


def _first_cost_month_index(row: StagedWorkbookRow) -> int:
    for index, column in enumerate(MONTH_COLS):
        if _norm(row.values.get(column)):
            return index
    return len(MONTH_COLS)


def _welfare_item_priority(row: StagedWorkbookRow) -> int:
    description = _search_text(_display_description(row.values.get(DESCRIPTION_COL)))
    for priority, tokens in enumerate(WELFARE_ITEM_ORDER_TOKENS):
        if any(_search_text(token) in description for token in tokens):
            return priority
    return len(WELFARE_ITEM_ORDER_TOKENS)


def _welfare_chronological_sort_key(row: StagedWorkbookRow) -> tuple[int, int, int, str]:
    return (
        _first_cost_month_index(row),
        _welfare_item_priority(row),
        int(row.original_row),
        _norm(_display_description(row.values.get(DESCRIPTION_COL))),
    )


def _new_hire_item_priority(row: StagedWorkbookRow) -> int | None:
    description = _display_description(row.values.get(DESCRIPTION_COL))
    uniform_key = uniform_item_key_for_rule(description)
    if uniform_key in NEW_HIRE_UNIFORM_ITEM_KEYS:
        return 0
    if uniform_key == "collapsible_cup":
        # Keep the new-worker and periodic cup rows as one adjacent pair,
        # immediately after the other new-hire uniform items.
        return 1
    searchable = _search_text(description)
    for priority, tokens in enumerate(NEW_HIRE_ITEM_ORDER_TOKENS, start=2):
        if any(_search_text(token) in searchable for token in tokens):
            return priority
    return None


def _cup_release_priority(row: StagedWorkbookRow) -> int:
    description = _display_description(row.values.get(DESCRIPTION_COL))
    if uniform_item_key_for_rule(description) != "collapsible_cup":
        return 0
    searchable = _search_text(description)
    return 1 if any(_search_text(token) in searchable for token in CUP_PERIODIC_TOKENS) else 0


def _new_hire_sort_key(row: StagedWorkbookRow) -> tuple[int, int, int, str]:
    priority = _new_hire_item_priority(row)
    return (
        priority if priority is not None else len(NEW_HIRE_ITEM_ORDER_TOKENS) + 2,
        _cup_release_priority(row),
        int(row.original_row),
        _norm(_display_description(row.values.get(DESCRIPTION_COL))),
    )


def _ordered_allocation_source_group(group: list[StagedWorkbookRow]) -> list[StagedWorkbookRow]:
    ordered = sorted(group, key=_source_block_sort_key) if _has_split_accounts(group) else list(group)
    new_hire_rows = [row for row in ordered if _new_hire_item_priority(row) is not None]
    remaining = [row for row in ordered if _new_hire_item_priority(row) is None]
    welfare_rows = [
        row
        for row in remaining
        if _norm(row.values.get(ACCOUNT_COL)) in WELFARE_ACCOUNT_CODES
    ]
    other_rows = [
        row
        for row in remaining
        if _norm(row.values.get(ACCOUNT_COL)) not in WELFARE_ACCOUNT_CODES
    ]
    return (
        sorted(welfare_rows, key=_welfare_chronological_sort_key)
        + sorted(new_hire_rows, key=_new_hire_sort_key)
        + other_rows
    )


def _ordered_source_group(
    group: list[StagedWorkbookRow], *, source_index: int | None = None
) -> list[StagedWorkbookRow]:
    if source_index == 0:
        # Facility rows use a documented business sequence, independent of the
        # physical row where a late reference layer happened to append them.
        return sorted(
            group,
            key=lambda row: (
                FACILITY_OUTPUT_ROW_PRIORITY.get(
                    int(row.original_row), len(FACILITY_OUTPUT_ROW_PRIORITY)
                ),
                int(row.source_row),
            ),
        )
    if source_index == 5:
        return _ordered_allocation_source_group(group)
    if not _has_split_accounts(group):
        return group
    return sorted(group, key=_source_block_sort_key)


def _duplicate_identity(row: StagedWorkbookRow) -> tuple[str, str]:
    return (_norm(row.values.get(ACCOUNT_COL)), _norm(_display_description(row.values.get(DESCRIPTION_COL))))


def _drop_staged_rows_duplicated_by_dynamic(
    staged: list[StagedWorkbookRow], dynamic_rows: list[StagedWorkbookRow]
) -> list[StagedWorkbookRow]:
    dynamic_identities = {
        identity
        for identity in (_duplicate_identity(row) for row in dynamic_rows)
        if identity[0] and identity[1]
    }
    if not dynamic_identities:
        return staged
    return [
        row
        for row in staged
        if _duplicate_identity(row) not in dynamic_identities
    ]


def apply_complete_v1_source_order_to_workbook(
    workbook_path: str | Path,
    *,
    start_row: int = helpers.FORM_SHARED_COST_START_ROW,
    clear_until_row: int | None = None,
    dynamic_allocation_rows: Iterable[dict[str, object]] | None = None,
    fiscal_periods: Iterable[str] | None = None,
    source_file_order: Iterable[str] | None = None,
    fiscal_year: int | None = None,
) -> dict[str, int]:
    """Ghi lại các dòng nghiệp vụ hoàn chỉnh (Complete-v1) theo từng khối tệp nguồn.

    Hàm thực hiện dọn dẹp các dòng dữ liệu cũ, gom nhóm theo từng tệp nguồn đầu vào,
    xắp xếp lại thứ tự dòng và bảo vệ các dòng QLNN (Quản lý Nhà nước từ dòng 30-37).

    Args:
        workbook_path: Đường dẫn tới file Excel HUB/FORM.
        start_row: Dòng bắt đầu ghi dữ liệu nghiệp vụ (mặc định: 38).
        clear_until_row: Dòng tối đa cần xóa dữ liệu cũ.
        source_file_order: Danh sách thứ tự tệp nguồn tùy chỉnh.
        fiscal_year: Năm tài chính (FY).

    Returns:
        dict chứa thống kê số lượng khối nguồn và số dòng đã ghi.
    """
    workbook_file = Path(workbook_path)
    wb = load_workbook(workbook_file)
    try:
        if source_file_order is None and fiscal_year not in (None, 2027):
            raise ValueError("FY2028 trở đi phải truyền thứ tự nguồn đã phân giải từ manifest; không dùng danh sách FY2027.")
        resolved_source_order = tuple(source_file_order or CANONICAL_SOURCE_FILE_ORDER)
        if len(resolved_source_order) < len(SOURCE_ROW_GROUPS):
            raise ValueError("Danh sách thứ tự nguồn không đủ nhóm nghiệp vụ.")
        try:
            ws = wb[helpers.find_hub_sheet_name(wb)]
        except ValueError:
            ws = wb.active
        form_contract = helpers.normalize_form_output_contract(wb)
        is_qlnn_layout = bool(form_contract["form_contract_detected"])
        protected_qlnn_rows = (
            {
                row: tuple(ws.cell(row, column).value for column in MANAGED_CLEAR_COLS)
                for row in range(30, 38)
            }
            if is_qlnn_layout
            else {}
        )
        # Rows 30–37 belong to the QLLN-owned layout in the current FORM.  This
        # writer only manages generated cost rows from row 38 onward.  Capture
        # their values/formulas now so any future regression fails safely before
        # the workbook is saved.
        # HubBuilder appends generated facts after the last occupied business
        # row.  The number differs by cost center, so a fixed cleanup boundary
        # (historically row 199) can leave duplicate allocations below it.
        # Structural lookup formulas in otherwise blank template rows do not
        # expand the heavy cleanup range; they are removed in a light pass.
        sheet_last_row = int(ws.max_row or (start_row - 1))
        effective_clear_until_row = max(
            int(clear_until_row or (start_row - 1)),
            _last_business_payload_row(ws, start_row),
        )
        source_rows_to_clear = _source_rows_to_clear(ws)
        staged = _collect_existing_source_order_rows(ws, start_row, effective_clear_until_row)
        if not staged:
            staged = _collect_staged_rows(ws, resolved_source_order)
        unmarked_facility_depreciation = _collect_unmarked_facility_depreciation_rows(
            ws,
            start_row,
            effective_clear_until_row,
            resolved_source_order[0],
        )
        existing_source_origins = {
            (row.source_file, row.original_row)
            for row in staged
            if row.source_order_managed
        }
        for row in unmarked_facility_depreciation:
            if (row.source_file, row.original_row) not in existing_source_origins:
                staged.append(row)
                existing_source_origins.add((row.source_file, row.original_row))
        # Do not let a recovered row also be emitted as an unmanaged row after
        # the source blocks.  The full range is cleared before rewrite, but this
        # exclusion decides which logical bucket owns the row.
        source_rows_to_clear.update(row.source_row for row in unmarked_facility_depreciation)
        dynamic_staged = _collect_dynamic_allocation_rows(dynamic_allocation_rows, fiscal_periods, resolved_source_order)
        has_dynamic_fixed_assets = any(
            row.source_file == resolved_source_order[1] for row in dynamic_staged
        )
        has_dynamic_nnn = any(
            row.source_file == resolved_source_order[6] for row in dynamic_staged
        )
        if has_dynamic_fixed_assets:
            staged = [
                row
                for row in staged
                if not (
                    row.source_file == resolved_source_order[1]
                    and row.original_row in (38, 42)
                )
            ]
        if has_dynamic_nnn:
            staged = [
                row
                for row in staged
                if row.source_file != resolved_source_order[6]
            ]
        staged = _drop_staged_rows_duplicated_by_dynamic(staged, dynamic_staged)
        staged.extend(dynamic_staged)
        invalid_nnn_rows = [
            row
            for row in staged
            if row.source_file == resolved_source_order[6]
            and _staged_row_has_month_payload(row)
            and not _norm(row.values.get(ACCOUNT_COL))
        ]
        if invalid_nnn_rows:
            original_rows = ", ".join(str(row.original_row) for row in invalid_nnn_rows)
            raise ValueError(
                "NNN paperwork có chi phí nhưng thiếu account code "
                f"(original_row={original_rows}); dừng xuất để tránh 経費➝NG."
            )
        preserved = _collect_preserved_unmanaged_rows(
            ws,
            start_row,
            effective_clear_until_row,
            source_rows_to_clear=source_rows_to_clear,
        )

        _clear_rows(ws, range(start_row, effective_clear_until_row + 1))
        _clear_rows(ws, source_rows_to_clear)
        tail_formulas_cleared = _clear_unused_template_formula_tail(
            ws,
            effective_clear_until_row + 1,
            sheet_last_row,
        )

        current_row = int(start_row)
        source_blocks_written = 0
        rows_written = 0
        blank_rows_written = 0

        for source_index, source_file in enumerate(resolved_source_order):
            group = [row for row in staged if row.source_file == source_file]
            if not group:
                continue
            if source_blocks_written:
                _clear_business_row(ws, current_row)
                blank_rows_written += 1
                current_row += 1
            for item in _ordered_source_group(group, source_index=source_index):
                _write_staged_row(ws, current_row, item)
                rows_written += 1
                current_row += 1
            source_blocks_written += 1

        preserved_rows_written = 0
        if preserved:
            if rows_written:
                _clear_business_row(ws, current_row)
                blank_rows_written += 1
                current_row += 1
            for item in preserved:
                _write_staged_row(ws, current_row, item)
                preserved_rows_written += 1
                current_row += 1

        layout_stats = _normalize_final_output_layout(ws, start_row, effective_clear_until_row)
        changed_protected_rows = [
            row
            for row, before in protected_qlnn_rows.items()
            if tuple(ws.cell(row, column).value for column in MANAGED_CLEAR_COLS) != before
        ]
        if changed_protected_rows:
            raise ValueError(
                "Lỗi bảo vệ FORM: bước sắp xếp kết quả đã làm thay đổi các dòng QLLN "
                f"{changed_protected_rows}. File không được lưu."
            )
        wb.save(workbook_file)
        return {
            "source_blocks_written": source_blocks_written,
            "rows_written": rows_written,
            "preserved_rows_written": preserved_rows_written,
            "blank_rows_written": blank_rows_written,
            "start_row": start_row,
            "end_row": current_row - 1 if rows_written or preserved_rows_written else start_row - 1,
            "cleared_through_row": effective_clear_until_row,
            "tail_formulas_cleared": tail_formulas_cleared,
            "nnn_rows_written": sum(
                1 for row in staged if row.source_file == resolved_source_order[6]
            ),
            **layout_stats,
        }
    finally:
        wb.close()
