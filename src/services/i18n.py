def t(key: str, **params: Any) -> str:
    """Tra cứu bản dịch theo key cho ngôn ngữ hiện tại, có fallback về tiếng Việt."""
    lang = _CURRENT_LANGUAGE
    template = TRANSLATIONS.get(lang, {}).get(key)
    if template is None:
        template = TRANSLATIONS.get(DEFAULT_LANGUAGE, {}).get(key, key)
    if params:
        try:
            return template.format(**params)
        except (KeyError, IndexError, ValueError):
            return template
    return template


def translate_for_language(key: str, language: str, **params: Any) -> str:
    """Tra cứu bản dịch theo key cho một ngôn ngữ cụ thể mà không làm thay đổi ngôn ngữ toàn cục.

    Hàm này không thực hiện fallback im lặng sang ngôn ngữ khác. Nếu ngôn ngữ không hợp lệ
    hoặc khóa không tồn tại, hàm sẽ ném ngoại lệ rõ ràng.
    """
    lang = str(language).strip().lower() if language else ""
    if lang not in SUPPORTED_LANGUAGES:
        raise ValueError(
            f"Ngôn ngữ '{language}' không được hỗ trợ. Các ngôn ngữ hợp lệ: {sorted(SUPPORTED_LANGUAGES)}"
        )
    lang_dict = TRANSLATIONS.get(lang, {})
    if key not in lang_dict:
        raise KeyError(
            f"Khóa bản dịch '{key}' không tồn tại trong từ điển ngôn ngữ '{lang}'."
        )
    template = lang_dict[key]
    if params:
        try:
            return template.format(**params)
        except (KeyError, IndexError, ValueError):
            return template
    return template



def translation_key_for_text(value: str, *, keys: tuple[str, ...] | None = None) -> str | None:
    """Return the key for an exact translated value, regardless of source language."""
    text = str(value or "").strip()
    if not text:
        return None
    candidates = keys or tuple(TRANSLATIONS.get(DEFAULT_LANGUAGE, {}))
    for key in candidates:
        for translations in TRANSLATIONS.values():
            if translations.get(key) == text:
                return key
    return None


def get_current_language() -> str:
    """Trả về mã ngôn ngữ đang hoạt động ('vi', 'ja', 'en')."""
    return _CURRENT_LANGUAGE


def set_current_language(lang: str) -> None:
    """Thiết lập ngôn ngữ giao diện hiện tại."""
    global _CURRENT_LANGUAGE
    candidate = str(lang or "").strip().lower()
    if candidate not in SUPPORTED_LANGUAGES:
        candidate = DEFAULT_LANGUAGE
    _CURRENT_LANGUAGE = candidate
    for listener in list(_LISTENERS):
        try:
            listener(_CURRENT_LANGUAGE)
        except Exception:
            pass


def get_supported_languages() -> list[tuple[str, str]]:
    """Trả về danh sách (code, display_name) của các ngôn ngữ được hỗ trợ."""
    return list(SUPPORTED_LANGUAGES.items())


def get_language_name(code: str) -> str:
    """Trả về tên hiển thị của mã ngôn ngữ."""
    return SUPPORTED_LANGUAGES.get(code, SUPPORTED_LANGUAGES[DEFAULT_LANGUAGE])


def get_language_code(name: str) -> str:
    """Chuyển đổi tên hiển thị sang mã ngôn ngữ."""
    for code, display_name in SUPPORTED_LANGUAGES.items():
        if display_name == name:
            return code
    return DEFAULT_LANGUAGE


def register_language_listener(callback: Callable[[str], None]) -> None:
    """Đăng ký callback nhận thông báo khi đổi ngôn ngữ."""
    if callback not in _LISTENERS:
        _LISTENERS.append(callback)


def unregister_language_listener(callback: Callable[[str], None]) -> None:
    """Hủy đăng ký callback."""
    if callback in _LISTENERS:
        _LISTENERS.remove(callback)
